defmodule WebTemplateWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :web_template

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_web_template_key",
    signing_salt: "aeKwL1+9",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # User-authenticated socket for application channels (`global`,
  # `user:<id>`). Auth is by signed Phoenix.Token from SharedData. No
  # longpoll fallback — clients on networks that block WebSockets fall
  # back to plain Inertia until the network is fixed.
  socket "/socket", WebTemplateWeb.UserSocket, websocket: true, longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :web_template,
    gzip: not code_reloading?,
    only: WebTemplateWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Self-served ex_doc. `mix docs` writes HTML + search index to `doc/`
  # (gitignored). `DocsIndexRedirect` bounces `/dev/docs` and
  # `/dev/docs/` to `/dev/docs/index.html` so relative links inside the
  # generated HTML resolve against the right directory.
  if Application.compile_env(:web_template, :dev_routes) do
    plug WebTemplateWeb.Plugs.DocsIndexRedirect
    plug Plug.Static, at: "/dev/docs", from: Path.expand("../../doc", __DIR__)
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :web_template
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug WebTemplateWeb.Router
end
